# 튜플 생성
t = (1, 2, 3)
print(t[0]) # 첫 번째 요소 출력

print(t + (4, 5)) # 합치기는 가능 → (1, 2, 3, 4, 5)
print(t * 2) #(1, 2, 3, 1, 2, 3) 중복 가능

print(len(t))  # 튜플의 길이 출력

# 튜플은 수정, 삭제 불가
# t[0] = 10  # 오류 발생
# del t[0]  # 오류 발생

# 1개 요소 생성
t1 = (1,)  # 쉼표 필요
print(t1)  # (1,)
print(type(t1))  # <class 'tuple'> 

# 1개 요소가 아닌 경우
t2 = (1)  # 1개 요소가 아닌 경우, 정수로 인식
print(t2)  # 1 출력
print(type(t2))  # <class 'int'> 

# 요일 튜플
days = ("월", "화", "수", "목", "금", "토", "일")
print(days)  # ('월', '화', '수', '목', '금', '토', '일')
print(days[0])  # '월' 출력, 첫 번째 요소 접근
print(days[-1])  # '일' 출력, 마지막 요소 접근

# 슬라이싱
print(days[1:4])  # ('화', '수', '목') 출력, 1번 인덱스부터 3번 인덱스까지
print(days[:3])  # ('월', '화', '수') 출력, 처음부터 2번 인덱스까지
print(days[4:])  # ('금', '토', '일') 출력, 4번 인덱스부터 끝까지
print(days[:])  # ('월', '화', '수', '목', '금', '토', '일') 출력, 전체 슬라이싱